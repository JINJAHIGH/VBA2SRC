"""内部モデルを比較用のUTF-8・LFテキストへ保存する。入力解析とOfficeへの書き戻しは扱わない。"""

from pathlib import Path

from .json_output import JSON文字列を作成, スキーマバージョン
from .paths import 保存名割当器, 安全な保存名

モジュール種類表 = {
    "standard": ("標準モジュール", ".bas"),
    "class": ("クラスモジュール", ".cls"),
    "document": ("ドキュメントモジュール", ".cls"),
    "form": ("ユーザーフォーム", ".txt"),
    "unknown": ("未分類", ".vba"),
}


# ── 1. 共通の保存形式と表示値 ──────────────────────────
def テキストを保存(パス, 内容):
    """UTF-8・BOMなし・LFで保存する。既存の空行は削除しない。"""
    パス = Path(パス)
    パス.parent.mkdir(parents=True, exist_ok=True)
    with パス.open("w", encoding="utf-8", newline="\n") as ストリーム:
        ストリーム.write(内容)


def JSONを保存(パス, プロジェクト識別子, ペイロード):
    """プロジェクト識別子とスキーマ版を添え、日本語項目のJSONへ変換する。"""
    データ = {"schema_version": スキーマバージョン, "project_id": プロジェクト識別子, **ペイロード}
    テキストを保存(パス, JSON文字列を作成(データ))


def 一行化(値):
    """改行・制御文字をエスケープし、レポートの1項目1行を保つ。"""
    if 値 is None:
        return "不明"
    if 値 == "":
        return "設定なし"
    テキスト = str(値)
    return "".join(
        "\\\\"
        if c == "\\"
        else f"\\u{ord(c):04x}"
        if ord(c) < 32 or 127 <= ord(c) <= 159 or c in "\u2028\u2029"
        else c
        for c in テキスト
    )


# ── 2. プロジェクトのコードと設定情報 ──────────────────────────
def プロジェクト情報を保存(フォルダ, 対象プロジェクト, 複数プロジェクト):
    """モジュールと設定情報を種類別に保存し、元の名前との対応を保持する。"""
    対象プロジェクト.保存先接頭辞 = f"プロジェクト/{対象プロジェクト.識別子}/" if 複数プロジェクト else ""
    ルート = フォルダ / 対象プロジェクト.保存先接頭辞
    種類別割当器 = {種類: 保存名割当器() for 種類 in モジュール種類表}
    モジュール一覧行 = []
    フォーム一覧 = []
    フォーム情報一覧 = {フォーム["name"]: フォーム for フォーム in 対象プロジェクト.フォーム一覧}
    for 対象モジュール in 対象プロジェクト.モジュール一覧:
        ディレクトリ, 拡張子 = モジュール種類表[対象モジュール.種類]
        ファイル名 = 種類別割当器[対象モジュール.種類].割当(対象モジュール.名前, 拡張子)
        相対参照 = f"{対象プロジェクト.保存先接頭辞}VBAソース/{ディレクトリ}/{ファイル名}"
        if 対象モジュール.コード is not None:
            対象モジュール.保存パス = 相対参照
            テキストを保存(フォルダ / 対象モジュール.保存パス, 対象モジュール.コード)
        # Pythonの属性名と公開JSONのスキーマを分離する。
        行情報 = {
            "name": 対象モジュール.名前,
            "kind": 対象モジュール.種類,
            "source_stream": 対象モジュール.抽出元ストリーム,
            "attributes": 対象モジュール.属性情報,
            "saved_path": 対象モジュール.保存パス,
            "metadata": 対象モジュール.メタデータ,
        }
        行情報["project_id"] = 対象プロジェクト.識別子
        行情報["codename"] = 対象モジュール.名前 if 対象モジュール.種類 == "document" else None
        行情報["codepage"] = 対象プロジェクト.コードページ
        行情報["source_status"] = "取得済み" if 対象モジュール.コード is not None else "読取失敗"
        モジュール一覧行.append(行情報)
        if 対象モジュール.種類 == "form":
            フォーム = フォーム情報一覧.get(対象モジュール.名前)
            if フォーム is not None:
                # 保存名の衝突があってもソースとフォーム情報は同じ名前で並べる。
                フォーム参照 = Path(相対参照).with_suffix(".json").as_posix()
                JSONを保存(フォルダ / フォーム参照, 対象プロジェクト.識別子, フォーム)
                フォーム一覧.append(
                    {"name": フォーム["name"], "saved_path": フォーム参照, "status": フォーム["status"]}
                )
    JSONを保存(
        ルート / "プロジェクト情報.json",
        対象プロジェクト.識別子,
        {
            "name": 対象プロジェクト.名前,
            "description": 対象プロジェクト.説明,
            "codepage": 対象プロジェクト.コードページ,
            "codec": 対象プロジェクト.文字コード,
            "modules_status": 対象プロジェクト.モジュール取得状態,
            "modules_expected": 対象プロジェクト.保存モジュール数,
            "source_origin": 対象プロジェクト.抽出元識別子,
            "forms": フォーム一覧,
            "sheets": 対象プロジェクト.シート一覧,
            "sheets_status": 対象プロジェクト.シート取得状態,
            "failures": sorted(set(対象プロジェクト.失敗一覧)),
            "diagnostics": sorted(set(対象プロジェクト.診断一覧)),
        },
    )
    JSONを保存(ルート / "モジュール一覧.json", 対象プロジェクト.識別子, {"modules": モジュール一覧行})
    JSONを保存(
        ルート / "条件付きコンパイル引数.json",
        対象プロジェクト.識別子,
        対象プロジェクト.条件付きコンパイル引数,
    )
    JSONを保存(
        ルート / "参照設定.json",
        対象プロジェクト.識別子,
        {"status": 対象プロジェクト.参照取得状態, "references": 対象プロジェクト.参照一覧},
    )
    JSONを保存(ルート / "保護情報.json", 対象プロジェクト.識別子, 対象プロジェクト.保護情報)


def 種類別コードを保存(フォルダ, プロジェクト一覧):
    """すべてのプロジェクトから、取得できたコードを種類ごとに一つのテキストへまとめる。"""
    フォルダ.mkdir(parents=True, exist_ok=True)
    種類別の章 = {}
    for 対象プロジェクト in プロジェクト一覧:
        for 対象モジュール in 対象プロジェクト.モジュール一覧:
            if 対象モジュール.コード is None:
                continue
            見出し = (
                f"' ===== モジュール：{一行化(対象モジュール.名前)}"
                f"（プロジェクト：{対象プロジェクト.識別子}） =====\n"
            )
            種類別の章.setdefault(対象モジュール.種類, []).extend((見出し, 対象モジュール.コード, "\n"))
    for 種類, 章一覧 in 種類別の章.items():
        表示名 = "フォーム" if 種類 == "form" else モジュール種類表[種類][0]
        テキストを保存(フォルダ / f"{表示名}.txt", "".join(章一覧))


# ── 3. 入力情報と出力の統括 ──────────────────────────
def 抽出結果を保存(フォルダ, 結果, *, 種類別出力=False):
    """入力情報、プロジェクト別成果物、種類別まとめを決定的な順序で保存する。"""
    フォルダ = Path(フォルダ)
    複数プロジェクト = len(結果.プロジェクト一覧) > 1
    # 名前定義はVBAプロジェクトではなくブックに属する。最上位へ一度だけ保存する。
    JSONを保存(
        フォルダ / "名前定義一覧.json",
        None,
        {
            **{キー: 値 for キー, 値 in 結果.名前定義情報.items() if キー != "items"},
            "defined_names": 結果.名前定義情報["items"],
        },
    )
    for 対象プロジェクト in 結果.プロジェクト一覧:
        プロジェクト情報を保存(フォルダ, 対象プロジェクト, 複数プロジェクト)

    # VBAなし・致命的失敗でも入力の判定結果を保存する。
    JSONを保存(
        フォルダ / "入力情報.json",
        None,
        {
            "original_filename": 結果.ファイル名,
            "sanitized_filename": 安全な保存名(結果.ファイル名),
            "format": 結果.形式,
            "vba": 結果.VBA有無,
            "status": 結果.状態,
            "failures": sorted(set(結果.失敗一覧)),
            "projects": [
                {"id": p.識別子, "origin": p.抽出元識別子, "saved_prefix": p.保存先接頭辞}
                for p in 結果.プロジェクト一覧
            ],
        },
    )
    if 種類別出力:
        種類別コードを保存(フォルダ / "VBAまとめ", 結果.プロジェクト一覧)
